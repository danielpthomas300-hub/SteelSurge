/* ==========================================================================
   AUTONOMOUS — program the robot with command blocks, then watch it run.
   Grab every yellow sample and score it in the green basket.
   Levels were generated by a solver (tools/autonomous_levels.js), so par is
   always the true minimum number of blocks.
   ========================================================================== */
(() => {
  "use strict";

  /* ---------------- Core rules (also used by the level generator in Node) ----------------
     Map:  #  wall   .  floor   B  basket   o  sample      Directions: 0 N, 1 E, 2 S, 3 W
     Blocks: F forward · L turn left · R turn right · G grab · S score · 2 / 3 = repeat next block */
  const DX = [0, 1, 0, -1], DY = [-1, 0, 1, 0];
  function parse(L) {
    const samples = [];
    let basket;
    L.map.forEach((row, y) => [...row].forEach((ch, x) => { if (ch === "o") samples.push([x, y]); if (ch === "B") basket = [x, y]; }));
    return { ...L, w: L.map[0].length, h: L.map.length, samples, basket };
  }
  /** Expands repeat blocks: "3F" → F F F. Returns [{cmd, src}] where src is the program index. */
  function expand(prog) {
    const out = [];
    for (let i = 0; i < prog.length; i++) {
      const b = prog[i];
      if (b === "2" || b === "3") { const n = +b, next = prog[i + 1]; if (next && next !== "2" && next !== "3") { for (let k = 0; k < n; k++) out.push({ cmd: next, src: i + 1, rep: i }); i++; } continue; }
      out.push({ cmd: b, src: i });
    }
    return out;
  }
  function initState(L) { return { x: L.start[0], y: L.start[1], d: L.start[2], hold: -1, picked: L.samples.map(() => false), scored: 0 }; }
  /** Applies one command. Returns { state, event } where event is "move" | "bump" | "turn" | "grab" | "score" | "miss". */
  function apply(L, st, cmd) {
    const s = { ...st, picked: st.picked.slice() };
    if (cmd === "L") { s.d = (s.d + 3) % 4; return { state: s, event: "turn" }; }
    if (cmd === "R") { s.d = (s.d + 1) % 4; return { state: s, event: "turn" }; }
    if (cmd === "F") {
      const nx = s.x + DX[s.d], ny = s.y + DY[s.d];
      if (nx < 0 || ny < 0 || nx >= L.w || ny >= L.h || L.map[ny][nx] === "#") return { state: s, event: "bump" };
      s.x = nx; s.y = ny; return { state: s, event: "move" };
    }
    if (cmd === "G") {
      const i = L.samples.findIndex(([x, y], k) => x === s.x && y === s.y && !s.picked[k]);
      if (i < 0 || s.hold >= 0) return { state: s, event: "miss" };
      s.picked[i] = true; s.hold = i; return { state: s, event: "grab" };
    }
    if (cmd === "S") {
      if (s.hold < 0 || s.x !== L.basket[0] || s.y !== L.basket[1]) return { state: s, event: "miss" };
      s.hold = -1; s.scored++; return { state: s, event: "score" };
    }
    return { state: s, event: "miss" };
  }
  function run(L, prog) { let st = initState(L); for (const { cmd } of expand(prog)) st = apply(L, st, cmd).state; return st; }
  const core = { parse, expand, initState, apply, run };
  if (typeof window === "undefined") { module.exports = core; return; }

  /* ======================================================================
     Game
     ====================================================================== */
  // [map rows "/"-separated, start "x,y,dir", par, repeat unlocked]
  const RAW = window.AUTONOMOUS_LEVELS;
  const LEVELS = RAW.map(([m, st, par, rep]) => parse({ map: m.split("/"), start: st.split(",").map(Number), par, repeat: !!rep }));
  const { Game, Sound, COLORS: C, roundRect, clamp, ease, store } = window.Arcade;
  const W = 800, H = 600, STEP = 0.32;
  const BLOCKS = {
    F: { label: "Forward", color: C.surge, icon: "↑" }, L: { label: "Turn left", color: C.violet, icon: "↺" }, R: { label: "Turn right", color: C.violet, icon: "↻" },
    G: { label: "Grab", color: C.amber, icon: "✋" }, S: { label: "Score", color: C.ok, icon: "★" }, 2: { label: "Repeat ×2", color: C.steelHi, icon: "×2" }, 3: { label: "Repeat ×3", color: C.steelHi, icon: "×3" },
  };
  const game = new Game({ id: "autonomous", width: W, height: H, pausable: false });
  const prog$ = store.get("ss-auto-progress", { stars: {}, last: 0 });
  const saveProg = () => {
    store.set("ss-auto-progress", prog$);
    const cleared = Object.keys(prog$.stars).length, total = Object.values(prog$.stars).reduce((a, b) => a + b, 0);
    if (cleared) store.set("ss-arcade-autonomous", { value: total, label: `${cleared}/${LEVELS.length} · ${total}★` });
    game.setHudBest(cleared ? `${total}★` : "—");
  };

  let L, li, program = [], st, steps = [], stepI = -1, stepT = 0, running = false, view, lastEvent = "", won = false;
  const limit = () => L.par + 5;

  function load(i) {
    li = clamp(i, 0, LEVELS.length - 1); L = LEVELS[li]; program = []; won = false; reset();
    prog$.last = li; saveProg();
    game.setHud("level", `${li + 1}/${LEVELS.length}`); game.setHud("par", String(L.par));
    game.setMessage(li === 0 ? "Add blocks below, then press Run. Drive onto the sample, Grab, then go to the basket and Score." : li === 4 ? "New block: Repeat. ×3 then Forward drives three squares using only two blocks." : `Score all ${L.samples.length} sample${L.samples.length > 1 ? "s" : ""} in ${L.par} blocks for 3 stars.`);
    renderUI(); game.start();
  }
  function reset() { running = false; st = initState(L); view = { x: st.x, y: st.y, d: st.d, px: st.x, py: st.y, pd: st.d }; steps = []; stepI = -1; stepT = 0; lastEvent = ""; }

  function runProgram() {
    if (won) return;
    if (running) { reset(); renderUI(); return; }
    if (!program.length) { game.setMessage("Your program is empty. Add some blocks first."); return; }
    reset(); steps = expand(program); running = true; stepI = 0; stepT = 0; begin(steps[0]); renderUI();
    Sound.select();
  }
  function begin(step) {
    const res = apply(L, st, step.cmd);
    view = { px: st.x, py: st.y, pd: st.d, x: res.state.x, y: res.state.y, d: res.state.d };
    st = res.state; lastEvent = res.event;
    const geo = layout(), [cx, cy] = cell(geo, st.x, st.y);
    if (res.event === "move") Sound.tone({ f: 330, f2: 400, dur: 0.07, type: "triangle", vol: 0.06 });
    else if (res.event === "turn") Sound.tone({ f: 500, dur: 0.05, type: "sine", vol: 0.05 });
    else if (res.event === "bump") { Sound.tone({ f: 130, dur: 0.1, type: "square", vol: 0.08 }); game.shake(4); }
    else if (res.event === "grab") { Sound.pickup(); game.particles.burst(cx, cy, { n: 12, color: C.amber, speed: 160, life: 0.5, gravity: 0 }); }
    else if (res.event === "score") { Sound.win(); game.particles.burst(cx, cy, { n: 30, color: C.ok, speed: 260, life: 0.7, gravity: 0 }); game.floaters.add("+1 SCORED", cx, cy - 20, C.ok, 18); }
    else if (res.event === "miss") { Sound.tone({ f: 220, f2: 160, dur: 0.12, type: "triangle", vol: 0.07 }); game.floaters.add(step.cmd === "G" ? "Nothing to grab" : "Can't score here", cx, cy - 20, C.danger, 15); }
    highlight(step.src);
  }
  function finish() {
    running = false; highlight(-1);
    if (st.scored === L.samples.length) return win();
    const left = L.samples.length - st.scored;
    game.setMessage(`Autonomous over: ${left} sample${left > 1 ? "s" : ""} not scored. Edit your program and run it again.`);
    Sound.tone({ f: 400, f2: 200, dur: 0.3, type: "sawtooth", vol: 0.08 });
    renderUI();
  }
  function win() {
    won = true;
    const n = program.length, stars = n <= L.par ? 3 : n <= L.par + 2 ? 2 : 1;
    prog$.stars[li] = Math.max(prog$.stars[li] || 0, stars); saveProg();
    const STAR = (on) => `<svg viewBox="0 0 24 24" fill="currentColor" class="${on ? "on" : ""}"><path d="m12 2 3.1 6.3 6.9 1-5 4.9 1.2 6.8L12 17.8 5.8 21l1.2-6.8-5-4.9 6.9-1z"/></svg>`;
    const last = li === LEVELS.length - 1;
    setTimeout(() => {
      game.showOverlay(`<span class="kicker">Level ${li + 1} · autonomous complete</span><h2>${stars === 3 ? "Perfect auto!" : "All samples scored"}</h2>
        <div class="stars">${STAR(stars >= 1)}${STAR(stars >= 2)}${STAR(stars >= 3)}</div>
        <p>${n} block${n === 1 ? "" : "s"} · par ${L.par}${stars < 3 ? ". Can you make it shorter?" : ""}</p>
        <div class="overlay-actions">${last ? '<button class="btn primary" data-primary>Level select</button>' : '<button class="btn primary" data-primary>Next level</button>'}<button class="btn" data-retry>Improve this one</button></div>`,
      { onPrimary: () => (last ? showLevels() : load(li + 1)) });
      game.overlay.querySelector("[data-retry]").addEventListener("click", () => { Sound.select(); won = false; reset(); game.hideOverlay(); renderUI(); });
    }, 600);
  }

  game.update = (dt) => {
    if (!running) return;
    stepT += dt;
    if (stepT >= STEP) {
      stepT = 0; stepI++;
      if (stepI >= steps.length || st.scored === L.samples.length) { finish(); return; }
      begin(steps[stepI]);
    }
  };

  function showLevels() {
    let top = 0; while (prog$.stars[top] != null && top < LEVELS.length - 1) top++;
    const btns = LEVELS.map((_, i) => `<button class="level-btn${prog$.stars[i] != null ? " done" : ""}${i === li ? " current" : ""}" data-level="${i}" ${i > top ? "disabled" : ""} aria-label="Level ${i + 1}">${i + 1}<small>${prog$.stars[i] ? "★".repeat(prog$.stars[i]) : ""}</small></button>`).join("");
    game.showOverlay(`<span class="kicker">Autonomous</span><h2>Choose a level</h2><div class="level-grid">${btns}</div><div class="overlay-actions"><button class="btn primary" data-primary>Play level ${top + 1}</button></div>`, { onPrimary: () => load(top) });
    game.overlay.querySelectorAll("[data-level]").forEach((b) => b.addEventListener("click", () => { Sound.select(); load(+b.dataset.level); }));
  }

  /* ---------------- Code UI ---------------- */
  const ui = document.getElementById("code-ui");
  document.getElementById("game").classList.add("side");
  function renderUI() {
    if (!L) return;
    const avail = ["F", "L", "R", "G", "S", ...(L.repeat ? ["3", "2"] : [])];
    ui.innerHTML = `
      <div class="code-panel"><h3>Blocks</h3><div class="code-palette">${avail.map((b) => `<button type="button" class="code-block" data-add="${b}" style="--b:${BLOCKS[b].color}" ${running || program.length >= limit() ? "disabled" : ""}><i>${BLOCKS[b].icon}</i>${BLOCKS[b].label}</button>`).join("")}</div></div>
      <div class="code-panel grow"><h3>Program <span>${program.length} / ${limit()} blocks</span></h3>
        <ol class="code-program">${program.length ? program.map((b, i) => `<li><button type="button" class="code-block in" data-del="${i}" style="--b:${BLOCKS[b].color}" ${running ? "disabled" : ""} aria-label="Remove ${BLOCKS[b].label}"><span class="n">${i + 1}</span><i>${BLOCKS[b].icon}</i>${BLOCKS[b].label}</button></li>`).join("") : '<li class="code-empty">Tap blocks to add them here.</li>'}</ol>
        <div class="code-actions"><button type="button" class="btn primary" data-run>${running ? "■ Stop" : "▶ Run autonomous"}</button><button type="button" class="btn" data-clear ${running || !program.length ? "disabled" : ""}>Clear</button></div>
      </div>`;
    game.setHud("blocks", String(program.length));
    ui.querySelectorAll("[data-add]").forEach((b) => b.addEventListener("click", () => add(b.dataset.add)));
    ui.querySelectorAll("[data-del]").forEach((b) => b.addEventListener("click", () => { program.splice(+b.dataset.del, 1); Sound.tone({ f: 300, dur: 0.05, type: "triangle", vol: 0.06 }); afterEdit(); }));
    ui.querySelector("[data-run]").addEventListener("click", runProgram);
    ui.querySelector("[data-clear]").addEventListener("click", clearProg);
  }
  function add(b) { if (running || won || program.length >= limit()) return; program.push(b); Sound.tone({ f: 600, dur: 0.05, type: "triangle", vol: 0.06 }); afterEdit(); }
  function clearProg() { if (running) return; program = []; afterEdit(); }
  function afterEdit() { if (!running) { st = initState(L); view = { x: st.x, y: st.y, d: st.d, px: st.x, py: st.y, pd: st.d }; } renderUI(); }
  function highlight(i) { ui.querySelectorAll("[data-del]").forEach((b) => b.classList.toggle("active", +b.dataset.del === i)); }

  /* ---------------- Rendering ---------------- */
  function layout() {
    const tile = Math.floor(Math.min((W - 80) / L.w, (H - 80) / L.h, 96));
    const bw = tile * L.w, bh = tile * L.h;
    return { tile, x: (W - bw) / 2, y: (H - bh) / 2, bw, bh };
  }
  const cell = (g, x, y) => [g.x + (x + 0.5) * g.tile, g.y + (y + 0.5) * g.tile];

  game.render = (ctx) => {
    ctx.fillStyle = C.bg; ctx.fillRect(-20, -20, W + 40, H + 40);
    if (!L) return;
    const g = layout(), t = game.time;
    // field
    ctx.fillStyle = "#0b1117"; roundRect(ctx, g.x - 12, g.y - 12, g.bw + 24, g.bh + 24, 14); ctx.fill(); ctx.strokeStyle = C.line; ctx.lineWidth = 2; ctx.stroke();
    for (let y = 0; y < L.h; y++) for (let x = 0; x < L.w; x++) {
      const px = g.x + x * g.tile, py = g.y + y * g.tile, ch = L.map[y][x];
      ctx.fillStyle = "#121a23"; ctx.fillRect(px, py, g.tile, g.tile);
      ctx.strokeStyle = "#1c2733"; ctx.lineWidth = 1; ctx.strokeRect(px + 0.5, py + 0.5, g.tile - 1, g.tile - 1);
      if (ch === "#") { const s = g.tile - 8; ctx.fillStyle = "#05080b"; roundRect(ctx, px + 4, py + 7, s, s - 3, 8); ctx.fill(); const gr = ctx.createLinearGradient(0, py, 0, py + s); gr.addColorStop(0, "#3a4859"); gr.addColorStop(1, "#253241"); ctx.fillStyle = gr; roundRect(ctx, px + 4, py + 4, s, s - 3, 8); ctx.fill(); }
    }
    // basket
    { const [bx, by] = cell(g, ...L.basket), s = g.tile * 0.78; ctx.save(); ctx.strokeStyle = C.ok; ctx.lineWidth = 3; ctx.shadowColor = C.ok; ctx.shadowBlur = 16; ctx.fillStyle = "rgba(61,220,151,0.12)";
      roundRect(ctx, bx - s / 2, by - s / 2, s, s, 10); ctx.fill(); ctx.stroke(); ctx.shadowBlur = 0;
      ctx.font = `700 ${g.tile * 0.18}px "JetBrains Mono", monospace`; ctx.textAlign = "center"; ctx.fillStyle = C.ok; ctx.fillText("BASKET", bx, by + s / 2 - 8);
      for (let i = 0; i < st.scored; i++) { ctx.fillStyle = C.amber; ctx.beginPath(); ctx.arc(bx - 14 + i * 14, by - 4, g.tile * 0.09, 0, Math.PI * 2); ctx.fill(); }
      ctx.restore(); }
    // samples
    L.samples.forEach(([x, y], i) => {
      if (st.picked[i]) return;
      const [cx, cy] = cell(g, x, y), r = g.tile * 0.17 + Math.sin(t * 3 + i) * 1.5;
      ctx.save(); ctx.fillStyle = C.amber; ctx.shadowColor = C.amber; ctx.shadowBlur = 14; ctx.beginPath();
      for (let k = 0; k < 6; k++) { const a = Math.PI / 3 * k + Math.PI / 6; ctx.lineTo(cx + Math.cos(a) * r, cy + Math.sin(a) * r); }
      ctx.closePath(); ctx.fill(); ctx.restore();
    });
    // robot (top-down)
    const k = running ? ease.outCubic(clamp(stepT / (STEP * 0.8), 0, 1)) : 1;
    let rx = view.px + (view.x - view.px) * k, ry = view.py + (view.y - view.py) * k;
    let dd = view.d - view.pd; if (dd > 2) dd -= 4; if (dd < -2) dd += 4;
    const ang = (view.pd + dd * k) * Math.PI / 2;
    if (running && lastEvent === "bump") { const b = Math.sin(clamp(stepT / STEP, 0, 1) * Math.PI) * 0.15; rx += DX[view.d] * b; ry += DY[view.d] * b; }
    const [cx, cy] = cell(g, rx, ry);
    drawTopBot(ctx, cx, cy, g.tile * 0.7, ang, st.hold >= 0);
    // start marker
    { const [sx, sy] = cell(g, L.start[0], L.start[1]); ctx.strokeStyle = "rgba(59,168,255,0.35)"; ctx.setLineDash([4, 4]); ctx.lineWidth = 2; ctx.strokeRect(sx - g.tile * 0.42, sy - g.tile * 0.42, g.tile * 0.84, g.tile * 0.84); ctx.setLineDash([]); }
    // timer bar (30s auto flavor)
    const prog = running ? clamp((stepI + stepT / STEP) / Math.max(1, steps.length), 0, 1) : 0;
    ctx.fillStyle = "#16202b"; roundRect(ctx, g.x, g.y + g.bh + 22, g.bw, 8, 4); ctx.fill();
    ctx.fillStyle = C.surge; roundRect(ctx, g.x, g.y + g.bh + 22, Math.max(8, g.bw * prog), 8, 4); ctx.fill();
    ctx.font = '600 11px "JetBrains Mono", monospace'; ctx.textAlign = "left"; ctx.fillStyle = C.dim; ctx.fillText(running ? `AUTO ${(30 * (1 - prog)).toFixed(1)}s` : "AUTO READY", g.x, g.y - 22);
    ctx.textAlign = "right"; ctx.fillText(`SCORED ${st.scored}/${L.samples.length}`, g.x + g.bw, g.y - 22);
    game.particles.draw(ctx); game.floaters.draw(ctx);
  };

  function drawTopBot(ctx, x, y, s, ang, holding) {
    ctx.save(); ctx.translate(x, y); ctx.rotate(ang);
    ctx.fillStyle = "#0b1016";
    for (const [wx, wy] of [[-0.5, -0.32], [0.38, -0.32], [-0.5, 0.18], [0.38, 0.18]]) { roundRect(ctx, wx * s, wy * s, s * 0.12, s * 0.16, 3); ctx.fill(); }
    ctx.shadowColor = C.surge; ctx.shadowBlur = 14; ctx.fillStyle = "#1b2633"; ctx.strokeStyle = C.surge; ctx.lineWidth = 3;
    roundRect(ctx, -s * 0.38, -s * 0.42, s * 0.76, s * 0.84, s * 0.16); ctx.fill(); ctx.stroke(); ctx.shadowBlur = 0;
    // intake at the front (up = facing direction)
    ctx.fillStyle = C.surge; ctx.beginPath(); ctx.moveTo(-s * 0.16, -s * 0.3); ctx.lineTo(s * 0.16, -s * 0.3); ctx.lineTo(0, -s * 0.5); ctx.closePath(); ctx.fill();
    ctx.fillStyle = "#0a0f15"; roundRect(ctx, -s * 0.22, -s * 0.12, s * 0.44, s * 0.26, s * 0.08); ctx.fill();
    if (holding) { ctx.fillStyle = C.amber; ctx.shadowColor = C.amber; ctx.shadowBlur = 10; ctx.beginPath(); ctx.arc(0, 0.02 * s, s * 0.1, 0, Math.PI * 2); ctx.fill(); }
    ctx.restore();
  }

  /* ---------------- Input ---------------- */
  game.onKey = (e) => {
    if (game.overlayOpen()) return;
    const map = { f: "F", ArrowUp: "F", ArrowLeft: "L", ArrowRight: "R", g: "G", s: "S" };
    if (e.key === "Enter") { e.preventDefault(); runProgram(); }
    else if (e.key === "Backspace") { e.preventDefault(); if (!running && program.length) { program.pop(); afterEdit(); } }
    else if (map[e.key]) { e.preventDefault(); add(map[e.key]); }
    else if ((e.key === "r" || e.key === "R") && !running) clearProg();
    else if (e.key === "l" || e.key === "L") showLevels();
  };
  document.querySelector("[data-act=restart]")?.addEventListener("click", clearProg);
  document.querySelector("[data-act=levels]")?.addEventListener("click", () => { Sound.select(); showLevels(); });

  saveProg();
  li = prog$.last || 0; L = LEVELS[li]; reset(); renderUI();
  game.setHud("level", `${li + 1}/${LEVELS.length}`); game.setHud("par", String(L.par));
  const isNew = !Object.keys(prog$.stars).length;
  game.showOverlay(`
    <span class="kicker">Steel Surge Arcade</span>
    <h2>Autonomous</h2>
    <p>Every FTC match starts with 30 seconds where the robot drives itself. Build a program from command blocks, press Run, and watch it go. Grab every sample and score it in the basket.</p>
    <div class="overlay-actions"><button class="btn primary" data-primary>${isNew ? "Start coding" : `Continue · level ${li + 1}`}</button>${isNew ? "" : '<button class="btn" data-lv>Levels</button>'}</div>`, { onPrimary: () => load(li) });
  game.overlay.querySelector("[data-lv]")?.addEventListener("click", () => { Sound.select(); showLevels(); });
})();
