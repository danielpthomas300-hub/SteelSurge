// Generates assets/js/arcade/autonomous-levels.js
//   node tools/autonomous_levels.js
// Every level's par is the exact minimum number of blocks (found by a shortest-path
// search over robot states), and the found solution is replayed through the game's own
// rules as a self-check.
const fs = require("fs");
const path = require("path");
const core = require("../assets/js/arcade/autonomous.js");

function rng(a) { return () => { a |= 0; a = (a + 0x6d2b79f5) | 0; let t = Math.imul(a ^ (a >>> 15), 1 | a); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; }; }

/** Dijkstra over (x, y, dir, picked-mask, holding). Actions cost 1 block; "3F" costs 2 when repeat is unlocked. */
function solve(L, repeat) {
  const n = L.samples.length, full = (1 << n) - 1;
  const key = (s) => `${s.x},${s.y},${s.d},${s.mask},${s.hold}`;
  const start = { x: L.start[0], y: L.start[1], d: L.start[2], mask: 0, hold: -1, scored: 0 };
  const toCore = (s) => ({ x: s.x, y: s.y, d: s.d, hold: s.hold, picked: L.samples.map((_, i) => !!(s.mask & (1 << i))), scored: s.scored });
  const fromCore = (c) => ({ x: c.x, y: c.y, d: c.d, hold: c.hold, mask: c.picked.reduce((m, p, i) => m | (p ? 1 << i : 0), 0), scored: c.scored });
  const actions = [["F", ["F"], 1], ["L", ["L"], 1], ["R", ["R"], 1], ["G", ["G"], 1], ["S", ["S"], 1]];
  if (repeat) actions.push(["3F", ["F", "F", "F"], 2], ["2F", ["F", "F"], 2]);
  const dist = new Map([[key(start), 0]]), prev = new Map();
  let frontier = [[0, start]];
  while (frontier.length) {
    frontier.sort((a, b) => a[0] - b[0]);
    const [c, s] = frontier.shift();
    if (c > dist.get(key(s))) continue;
    if (s.scored === n && s.mask === full) {
      const sol = []; let k = key(s); while (prev.has(k)) { const [pk, a] = prev.get(k); sol.unshift(a); k = pk; } return { cost: c, sol };
    }
    for (const [name, cmds, cost] of actions) {
      let cs = toCore(s), changed = false;
      for (const cmd of cmds) { const r = core.apply(L, cs, cmd); if (r.event !== "bump" && r.event !== "miss") changed = true; cs = r.state; }
      if (!changed) continue;
      const ns = fromCore(cs), k = key(ns), nc = c + cost;
      if (!dist.has(k) || nc < dist.get(k)) { dist.set(k, nc); prev.set(k, [key(s), name]); frontier.push([nc, ns]); }
    }
  }
  return null;
}

function make(r, w, h, samples, density, repeat, minPar, maxPar) {
  for (let tries = 0; tries < 6000; tries++) {
    const g = Array.from({ length: h }, () => Array.from({ length: w }, () => (r() < density ? "#" : ".")));
    const free = []; for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) if (g[y][x] === ".") free.push([x, y]);
    if (free.length < samples + 3) continue;
    const pick = () => free.splice((r() * free.length) | 0, 1)[0];
    const st = pick(), b = pick(); g[b[1]][b[0]] = "B";
    for (let i = 0; i < samples; i++) { const s = pick(); g[s[1]][s[0]] = "o"; }
    const L = core.parse({ map: g.map((row) => row.join("")), start: [st[0], st[1], (r() * 4) | 0] });
    const res = solve(L, repeat);
    if (!res || res.cost < minPar || res.cost > maxPar) continue;
    if (repeat && !res.sol.some((a) => a === "3F")) continue; // repeat levels should reward using Repeat
    // Self-check: replay the solution with the real rules.
    const prog = res.sol.flatMap((a) => (a === "3F" ? ["3", "F"] : a === "2F" ? ["2", "F"] : [a]));
    const end = core.run(L, prog);
    if (end.scored !== L.samples.length || prog.length !== res.cost) throw new Error("self-check failed");
    return { map: L.map, start: L.start, par: res.cost, repeat, sol: prog.join("") };
  }
  throw new Error(`no level for ${w}x${h} s=${samples} par ${minPar}-${maxPar}`);
}

const plan = [
  // w, h, samples, wall density, repeat?, par range
  [4, 4, 1, 0.0, false, 5, 6], [5, 5, 1, 0.12, false, 6, 7], [5, 5, 1, 0.2, false, 8, 9], [5, 5, 2, 0.1, false, 10, 12],
  [6, 5, 1, 0.1, true, 7, 8], [6, 6, 2, 0.14, true, 11, 13], [6, 6, 2, 0.18, true, 13, 15], [6, 6, 3, 0.12, true, 16, 21],
  [7, 6, 2, 0.18, true, 15, 19], [7, 7, 3, 0.14, true, 19, 24], [7, 7, 3, 0.18, true, 21, 26], [7, 7, 3, 0.2, true, 23, 30],
  // Expert pack (levels 13–18)
  [8, 7, 3, 0.16, true, 24, 30], [8, 8, 3, 0.16, true, 25, 32], [8, 8, 3, 0.2, true, 26, 33],
  [8, 8, 4, 0.14, true, 28, 36], [8, 8, 4, 0.18, true, 30, 38], [9, 8, 4, 0.18, true, 32, 42],
];
const r = rng(27254);
const levels = plan.map((p, i) => { const L = make(r, ...p); console.error(`L${i + 1}: par ${L.par}  ${L.sol}`); return L; });
const out = "// Generated by tools/autonomous_levels.js. Do not edit by hand.\n// [map rows, start \"x,y,dir\", par, repeat unlocked, an optimal solution]\nwindow.AUTONOMOUS_LEVELS = " +
  JSON.stringify(levels.map((L) => [L.map.join("/"), L.start.join(","), L.par, L.repeat ? 1 : 0, L.sol])) + ";\n";
fs.writeFileSync(path.join(__dirname, "../assets/js/arcade/autonomous-levels.js"), out);
console.error("wrote autonomous-levels.js");
